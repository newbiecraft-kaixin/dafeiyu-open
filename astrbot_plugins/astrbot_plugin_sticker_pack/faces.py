class FaceMixin:
    # ---------- 语义配脸：从正文切词判断情绪，再挑一张真人常用的脸 ----------
    def _face_ok(self, name: str) -> bool:
        """库里真有这张脸，且在白名单里（白名单外的一张都不许发）。"""
        item = self.stickers.get(name)
        if not item or item.get("kind") != "face":
            return False
        if self.config.get("face_whitelist_only", True) and name not in COMMON_FACES:
            return False
        return True

    def _canon_face(self, name: str) -> str:
        """模型写了冷门脸（:斜眼笑:）→ 换成真人真会发的近似脸；实在没有就返回空。"""
        if self._face_ok(name):
            return name
        if not self.config.get("face_whitelist_only", True):
            item = self.stickers.get(name)
            return name if item and item.get("kind") == "face" else ""
        sub = FACE_SUBSTITUTE.get(name)
        if sub and self._face_ok(sub):
            return sub
        return ""

    def _mark_face_used(self, umo: str, name: str) -> None:
        rec = self._face_recent.setdefault(umo, [])
        rec.append(name)
        del rec[:-4]  # 只记最近 4 张，够轮换了
        self._save_rotate()

    def _pick_semantic_face(self, text: str, umo: str) -> str:
        """正文语义 -> 一张脸；挑不到返回空串。正文一个字都不改。"""
        # 先剥掉 :笑哭: 这类占位符：它们是从 emoji 换过来的「表情名」，
        # 不是正文情绪。不剥的话「😂😭😡 三连」会因为占位符里有「哭」字
        # 被判成难过、配一张大哭，把三个 emoji 本身的情绪盖掉。
        text = PLACEHOLDER.sub(" ", text)
        if NEG_MOOD_RE.search(text):
            return ""
        recent = self._face_recent.get(umo, [])
        for words, faces in FACE_MOOD_RULES:
            if not any(w in text for w in words):
                continue
            pool = [f for f in faces if self._face_ok(f)]
            if not pool:
                continue
            fresh = [f for f in pool if f not in recent]
            name = random.choice(fresh or pool)
            return name
        return ""
