# ---------- 从 QQ 官方 face_config.json 同步来的表情目录 ----------
# 手写表的通病是漏：QQ 本体有 282 条系统表情、165 条官方 emoji 映射，
# 靠手抄只能覆盖三分之一，而且抄错的名字（「破涕为笑」「强」「可爱」这类
# 库里根本没有的脸）在 _preconvert 里会被 `name in self.stickers` 静默丢掉，
# 表现就是「AI 打了 emoji 却没表情」。
# 所以这里直接吃 tools/sync_qq_faces.py 生成的 face_catalog.json，
# 上面两张手写表退居兜底（目录文件丢了也能跑）。
def _load_face_catalog() -> dict:
    path = os.path.join(PLUGIN_DIR, "face_catalog.json")
    try:
        with open(path, encoding="utf-8") as fh:
            data = json.load(fh)
        if isinstance(data, dict) and data.get("emoji"):
            return data
        logger.warning("[sticker_pack] face_catalog.json 内容为空，用内置表兜底")
    except FileNotFoundError:
        logger.warning("[sticker_pack] 缺 face_catalog.json，用内置表兜底")
    except Exception as e:  # noqa: BLE001
        logger.warning(f"[sticker_pack] face_catalog.json 读取失败: {type(e).__name__}: {e}")
    return {}


